// Full HTML document. `chrome: false` leaves out the header (used by the home page).
export function layout(site, { path, title, bodyClass, lang = 'en', description, main, mainClass = '', before = '', chrome = true, noindex = false, extraCss = [], alternates = null, head = '' }) {
  const fullTitle = title ? `${title} - ${site.name}` : (site.title || site.name);
  const desc = description || site.description;
  const url = site.url + path;
  // Same page in the other languages: tells search engines which version to show whom.
  const hreflang = (alternates || []).map((a) => `\n  <link rel="alternate" hreflang="${a.code}" href="${attr(site.url + a.href)}">`).join('')
    + (alternates?.length > 1 && !noindex ? `\n  <link rel="alternate" hreflang="x-default" href="${attr(site.url + alternates[0].href)}">` : '');
  const image = site.image ? `\n  <meta property="og:image" content="${attr(site.url + site.image)}">` : '';
  return `<!doctype html>
<!-- Generated by build/build.mjs from the content/ folder. Edit the content files, not this page. -->
<html lang="${lang}">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>${esc(fullTitle)}</title>
  <meta name="description" content="${attr(desc)}">${noindex ? '\n  <meta name="robots" content="noindex">' : ''}
  <meta property="og:type" content="website">
  <meta property="og:title" content="${attr(fullTitle)}">
  <meta property="og:description" content="${attr(desc)}">
  <meta property="og:url" content="${attr(url)}">${image}
  <meta name="twitter:card" content="summary_large_image">
  <link rel="canonical" href="${attr(url)}">${hreflang}
  <link rel="icon" href="/assets/img/favicon-light.png" media="(prefers-color-scheme: light)">
  <link rel="icon" href="/assets/img/favicon-dark.png" media="(prefers-color-scheme: dark)">
  <link rel="stylesheet" href="${v('/assets/css/tokens.css')}">
  <link rel="stylesheet" href="${v('/assets/css/style.css')}">
  <link rel="stylesheet" href="${v('/assets/css/type.css')}">
  <link rel="stylesheet" href="${v('/assets/css/fun.css')}">${extraCss.map((h) => `\n  <link rel="stylesheet" href="${v(h)}">`).join('')}
  <script>${THEME_BOOT}</script>${stageBoot(before + main)}
  <script src="${v('/assets/js/main.js')}" defer></script>
  <script src="${v('/assets/js/fun.js')}" defer></script>${head ? '\n' + indent(head, 2) : ''}
</head>
<body class="${bodyClass}${site.menu_desktop === 'inline' ? '' : ' menu-everywhere'}">
${before ? before + '\n' : ''}${chrome ? header(site, alternates) + '\n' : ''}  <main${mainClass ? ` class="${mainClass}"` : ''}>
${indent(main, 4)}
  </main>
${footer(site)}
</body>
</html>
`;
}

// When the previous page showed the same background photo or video (e.g. switching
// language), it stays lit instead of fading in again. Runs before the first paint.
function stageBoot(html) {
  const m = html.match(/class="(?:bg-video[^"]*|bio-photo)"[^>]*>\s*<(?:video|img) src="([^"]+)"/);
  if (!m) return '';
  return `\n  <script>try{if(sessionStorage.getItem('stage')===${JSON.stringify(m[1].replace(/^\//, '')).replace(/</g, '\\u003c')})document.documentElement.classList.add('stage-lit')}catch(e){}</script>`;
}

// Light mode is a test: the site stays dark unless a visitor picks light with the
// dark/light switch next to the language switch (remembered in the browser) or opens a page with ?theme=light.
// This runs before the page paints, so there is no dark/light flash.
const THEME_BOOT = `(function(){try{var q=location.search.match(/[?&]theme=(light|dark)/);if(q)localStorage.setItem('theme',q[1]);if(localStorage.getItem('theme')==='light')document.documentElement.setAttribute('data-theme','light')}catch(e){}})()`;

export function header(site, alternates = null) {
  const ui = site.ui || {};
  return `  <header class="site-header">
    <a class="name" href="${attr(site.home || '/')}">${esc(site.name)}</a>
    <nav class="header-nav" aria-label="${attr(ui.main_menu || 'Main')}">
${site.nav.map((n) => `      <a href="${attr(n.url)}">${esc(n.label)}</a>`).join('\n')}
    </nav>
    ${topRight(site, alternates)}
    <button class="menu-toggle" aria-label="${attr(ui.menu || 'Menu')}" aria-expanded="false" aria-controls="menu"><span></span><span></span><span></span></button>
    <div class="menu" id="menu">
      <div class="home-main">
${indent(homeView(site), 8)}
      </div>
${alternates?.length > 1 ? '    ' + langSwitch(site, alternates, 'menu-langs') + '\n' : ''}${indent(footer(site), 4)}
    </div>
  </header>`;
}

// The home page view: big name at the top, big menu at the bottom. The mobile menu
// opens to this same view, so the two look identical.
export function homeView(site) {
  return `<a class="home-name" href="${attr(site.home || '/')}">${esc(site.name)}</a>
<nav class="home-nav" aria-label="${attr((site.ui || {}).main_menu || 'Main')}">
${site.nav.map((n) => `  <a href="${attr(n.url)}">${esc(n.label)}</a>`).join('\n')}
</nav>`;
}

// Top right corner: language switch, then the "time in Munich" clock (desktop only).
export function topRight(site, alternates = null) {
  return `<div class="top-right">${alternates?.length > 1 ? langSwitch(site, alternates) : ''}${clock(site)}</div>`;
}

// "EN DE RU": the same page in each language, the current one marked.
export function langSwitch(site, alternates, extraClass = '') {
  const ui = site.ui || {};
  return `<nav class="lang-switch${extraClass ? ' ' + extraClass : ''}" aria-label="${attr(ui.language || 'Language')}">${alternates.map((a) =>
    `<a href="${attr(a.href)}" hreflang="${a.code}" lang="${a.code}" data-lang="${a.code}"${a.code === site.lang ? ' aria-current="true"' : ''}>${esc(a.label)}</a>`).join('')}</nav>`;
}

// First visit to the home page: a full-screen language choice on black, before the
// home page shows. The choice is remembered (main.js), and later visits to the root
// go straight to that language. Without JavaScript the picker never shows.
export function langPickerHead(alternates) {
  const map = JSON.stringify(Object.fromEntries(alternates.map((a) => [a.code, a.href])));
  return `<script>
(function () {
  try {
    var l = localStorage.getItem('lang'), m = ${map};
    if (!l) document.documentElement.classList.add('choose-lang');
    else if (m[l] && m[l] !== location.pathname) location.replace(m[l]);
  } catch (e) {}
})();
</script>`;
}

export function langPicker(alternates) {
  return `<div class="lang-picker" role="dialog" aria-modal="true" aria-label="Language / Sprache / Язык">
  <nav>${alternates.map((a) => `<a href="${attr(a.href)}" hreflang="${a.code}" lang="${a.code}" data-lang="${a.code}">${esc(a.code)}</a>`).join('')}</nav>
</div>`;
}

