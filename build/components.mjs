// Full HTML document. `chrome: false` leaves out the header (used by the home page).
export function layout(site, { path, title, bodyClass, lang = 'en', description, main, before = '', chrome = true, noindex = false, extraCss = [] }) {
  const fullTitle = title ? `${title} - ${site.name}` : site.name;
  const desc = description || site.description;
  const url = site.url + path;
  const image = site.image ? `\n  <meta property="og:image" content="${attr(site.url + site.image)}">` : '';
  return `<!doctype html>
<!-- Generated by build/build.mjs from the content/ folder. Edit the content files, not this page. -->
<html lang="${lang}">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>${esc(fullTitle)}</title>
  <meta name="description" content="${attr(desc)}">${noindex ? '\n  <meta name="robots" content="noindex">' : ''}
  <meta property="og:type" content="website">
  <meta property="og:title" content="${attr(fullTitle)}">
  <meta property="og:description" content="${attr(desc)}">
  <meta property="og:url" content="${attr(url)}">${image}
  <meta name="twitter:card" content="summary_large_image">
  <link rel="canonical" href="${attr(url)}">
  <link rel="icon" href="/assets/img/favicon-light.png" media="(prefers-color-scheme: light)">
  <link rel="icon" href="/assets/img/favicon-dark.png" media="(prefers-color-scheme: dark)">
  <link rel="stylesheet" href="${v('/assets/css/tokens.css')}">
  <link rel="stylesheet" href="${v('/assets/css/style.css')}">
  <link rel="stylesheet" href="${v('/assets/css/type.css')}">${extraCss.map((h) => `\n  <link rel="stylesheet" href="${v(h)}">`).join('')}
  <script src="${v('/assets/js/main.js')}" defer></script>
</head>
<body class="${bodyClass}">
${before ? before + '\n' : ''}${chrome ? header(site) + '\n' : ''}  <main>
${indent(main, 4)}
  </main>
${footer(site)}
</body>
</html>
`;
}

export function header(site) {
  return `  <header class="site-header">
    <a class="name" href="/">${esc(site.name)}</a>
    <nav class="header-nav" aria-label="Main">
${site.nav.map((n) => `      <a href="${attr(n.url)}">${esc(n.label)}</a>`).join('\n')}
    </nav>
    ${clock()}
    <button class="menu-toggle" aria-label="Menu" aria-expanded="false" aria-controls="menu"><span></span><span></span><span></span></button>
    <nav class="menu" id="menu" aria-label="Main">
${site.nav.map((n) => `      <a href="${attr(n.url)}">${esc(n.label)}</a>`).join('\n')}
    </nav>
  </header>`;
}

// "Time in Munich" clock shown at the top right on wide screens (filled in by main.js).
export function clock() {
  return `<p class="clock" aria-hidden="true">Time in Munich <b data-clock>--:--</b></p>`;
}

export function footer(site) {
  return `  <footer class="site-footer">
${site.footer.map((n) => `    <a href="${attr(n.url)}">${esc(n.label)}</a>`).join('\n')}
  </footer>`;
}

// Big uppercase heading, e.g. "Director", "Works".
export function pageTitle(text, extraClass = '') {
  return `<h1 class="page-title${extraClass ? ' ' + extraClass : ''}">${esc(text)}</h1>`;
}

// Small bold uppercase line. `html` is already-safe markup.
export function label(html, { tag = 'h2', extraClass = '' } = {}) {
  return `<${tag} class="label${extraClass ? ' ' + extraClass : ''}">${html}</${tag}>`;
}

// Fixed full-screen looping video behind a production page.
export function bgVideo(src) {
  return `  <div class="bg-video" aria-hidden="true"><video src="${attr(src)}" autoplay muted loop playsinline preload="auto"></video></div>`;
}

// List of productions on the left of theater/playwriting pages. The current one opens
// and shows its summary lines.
export function workList(items, currentSlug) {
  const li = items.map((it) => {
    if (it.slug !== currentSlug) return `  <li><a href="${attr(it.url)}">${esc(it.title)}</a></li>`;
    const lines = it.summaryHtml.map((p) => `      <p>${p}</p>`);
    if (it.linksHtml) lines.push(`      <p class="work-links">${it.linksHtml}</p>`);
    const summary = lines.length ? `\n    <div class="summary">\n${lines.join('\n')}\n    </div>\n  ` : '';
    return `  <li class="current"><a href="${attr(it.url)}" aria-current="page">${esc(it.title)}</a>${summary}</li>`;
  });
  return `<ul class="nav-list">\n${li.join('\n')}\n</ul>`;
}

// Two-column layout: list on the left, text on the right.
export function split(left, right = '') {
  return `<div class="split">\n${indent(left, 2)}${right ? '\n' + indent(right, 2) : ''}\n</div>`;
}

export function detail(blocks) {
  return `<div class="detail">\n${blocks.map((b) => '  ' + b).join('\n')}\n</div>`;
}

// Audio player with play/pause, seek bar, time and download link.
export function player(src) {
  return `<div class="player" data-src="${attr(src)}">
  <audio preload="metadata" src="${attr(src)}"></audio>
  <div class="player-row">
    <button type="button" aria-label="Play audio"><svg viewBox="0 0 16 16" aria-hidden="true"><path class="icon-play" d="${PLAY_ICON}"/></svg></button>
    <div class="bar" role="slider" aria-label="Seek" tabindex="0"><i></i></div>
  </div>
  <div class="player-meta">
    <span class="time">0:00</span>
    <a class="download" href="${attr(src)}" download>DOWNLOAD</a>
  </div>
</div>`;
}

// One voice role card: still image, character name, title of the film/game.
export function workCard(role) {
  return `<article class="work">
  <img src="${attr(role.image)}" alt="${attr(`${role.character} — ${role.title}`)}" loading="lazy" width="1170" height="324">
  <h3>${esc(role.character)}</h3>
  <p>${esc(role.title)}</p>
</article>`;
}

export function workGrid(roles) {
  return `<div class="works">\n${roles.map((r) => indent(workCard(r), 2)).join('\n')}\n</div>`;
}

export function indent(s, n) {
  const pad = ' '.repeat(n);
  return s.split('\n').map((l) => (l ? pad + l : l)).join('\n');
}

// Email address that copies itself to the clipboard on click (filled in by main.js).
// The address is stored reversed and base64-encoded, so it isn't a plain mailto link
// that spam bots can pick up. With `label`, the button shows that text; without it,
// it shows the address itself. <noscript> keeps a readable fallback.
export function copyEmail(address, { label, extraClass = '' } = {}) {
  const enc = Buffer.from([...address].reverse().join('')).toString('base64');
  const fallback = esc(address.replace('@', ' [at] '));
  const cls = 'copy-email' + (extraClass ? ' ' + extraClass : '');
  return label
    ? `<button type="button" class="${cls}" data-e="${enc}" title="Copy email address">${esc(label)}</button>`
    : `<button type="button" class="${cls}" data-e="${enc}" data-show title="Copy email address">${fallback}</button>`;
}
